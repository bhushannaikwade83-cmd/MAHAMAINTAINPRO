/// Photo for a category tile (Home grid, All Categories, Search, category header).
/// Returns null when no photo was supplied for that category - caller should
/// fall back to the emoji.
String? getCategoryIcon(String categoryName) => _categoryIcons[categoryName];

/// Photo for one service inside a category's list. Mirrors [getCategoryIcon]
/// for most categories; "Electrician, Plumber & Carpenter" has two supplied
/// photos, so plumbing-sounding services get the plumber photo and the rest
/// get the electrician photo.
String? getServiceIcon(String categoryName, String serviceName) {
  if (categoryName == 'Electrician, Plumber & Carpenter') {
    const plumberKeywords = [
      'plumber', 'tap', 'mixer', 'toilet', 'drainage', 'basin', 'sink',
      'pipe', 'bathroom fitting', 'water tank', 'motor',
    ];
    final lower = serviceName.toLowerCase();
    if (plumberKeywords.any((k) => lower.contains(k))) {
      return 'assets/images/categories/plumber.jpeg';
    }
    return 'assets/images/categories/electrician.jpeg';
  }
  return _categoryIcons[categoryName];
}

